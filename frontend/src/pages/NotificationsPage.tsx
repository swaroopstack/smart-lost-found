import { Link, useSearchParams } from "react-router-dom";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import {
  Bell,
  Check,
  CheckCircle,
  ClipboardText,
  Sparkle,
  XCircle,
} from "@phosphor-icons/react";
import { endpoints } from "@/api/endpoints";
import type { NotificationItem, Role } from "@/api/types";
import { useAuth } from "@/auth/AuthProvider";
import { PageHeader } from "@/components/ui/PageHeader";
import { Button } from "@/components/ui/Button";
import { SegmentedControl } from "@/components/ui/SegmentedControl";
import { EmptyState, ErrorState } from "@/components/ui/States";
import { SkeletonRows } from "@/components/ui/Skeleton";
import { useToast } from "@/components/ui/Toast";
import { formatRelative } from "@/lib/format";
import { cn } from "@/lib/cn";

const iconFor = (type: string) => {
  switch (type) {
    case "MATCH_FOUND":
      return Sparkle;
    case "CLAIM_SUBMITTED":
      return ClipboardText;
    case "CLAIM_APPROVED":
      return CheckCircle;
    case "CLAIM_REJECTED":
      return XCircle;
    default:
      return Bell;
  }
};

const toneFor = (type: string): string => {
  switch (type) {
    case "MATCH_FOUND":
      return "bg-brand-soft text-brand-strong";
    case "CLAIM_APPROVED":
      return "bg-success-soft text-success-strong";
    case "CLAIM_REJECTED":
      return "bg-danger-soft text-danger-strong";
    case "CLAIM_SUBMITTED":
      return "bg-accent-soft text-accent-strong";
    default:
      return "bg-surface-sunken text-ink-soft";
  }
};

function hrefFor(item: NotificationItem, role: Role): string | null {
  const reportId = item.payload.report_id;
  if (typeof reportId === "number") return `/reports/${reportId}`;

  const matchId = item.payload.match_id;
  if (typeof matchId === "number" && (role === "STAFF" || role === "ADMIN")) {
    return `/admin/matches/${matchId}`;
  }

  if (typeof item.payload.claim_id === "number") {
    return role === "STUDENT" ? "/my-claims" : "/admin/claims";
  }

  return null;
}

export function NotificationsPage() {
  const { user } = useAuth();
  const toast = useToast();
  const queryClient = useQueryClient();
  const [params, setParams] = useSearchParams();
  const unreadOnly = params.get("filter") === "unread";

  const notificationsQuery = useQuery({
    queryKey: ["notifications", { unreadOnly }],
    queryFn: () =>
      endpoints.notifications({ unread_only: unreadOnly || undefined, page_size: 50 }),
  });

  const unreadQuery = useQuery({
    queryKey: ["notifications", "unread-count"],
    queryFn: endpoints.unreadCount,
  });

  const invalidate = () => {
    queryClient.invalidateQueries({ queryKey: ["notifications"] });
  };

  const markRead = useMutation({
    mutationFn: (id: number) => endpoints.markNotificationRead(id),
    onSuccess: invalidate,
    onError: () => toast.error("Could not update the notification"),
  });

  const markAll = useMutation({
    mutationFn: () => endpoints.markAllNotificationsRead(),
    onSuccess: () => {
      toast.success("All caught up", "Every notification is marked as read.");
      invalidate();
    },
    onError: () => toast.error("Could not mark everything as read"),
  });

  const unread = unreadQuery.data?.unread ?? 0;

  return (
    <div className="space-y-6">
      <PageHeader
        title="Notifications"
        description="Matches, claim decisions and desk updates. Notifications are generated by the system, not by other students."
        actions={
          <Button
            variant="secondary"
            onClick={() => markAll.mutate()}
            disabled={unread === 0}
            loading={markAll.isPending}
            icon={<Check size={16} aria-hidden="true" />}
          >
            Mark all as read
          </Button>
        }
      />

      <div className="-mx-1 overflow-x-auto px-1 pb-1">
        <SegmentedControl
          label="Notification filter"
          value={unreadOnly ? "unread" : "all"}
          options={[
            { value: "all", label: "All" },
            { value: "unread", label: "Unread", count: unread },
          ]}
          onChange={(value) => {
            const next = new URLSearchParams(params);
            if (value === "unread") next.set("filter", "unread");
            else next.delete("filter");
            setParams(next, { replace: true });
          }}
        />
      </div>

      {notificationsQuery.isError ? (
        <ErrorState error={notificationsQuery.error} onRetry={() => notificationsQuery.refetch()} />
      ) : notificationsQuery.isPending ? (
        <SkeletonRows rows={5} />
      ) : notificationsQuery.data.items.length === 0 ? (
        <EmptyState
          icon={<Bell size={22} aria-hidden="true" />}
          title={unreadOnly ? "No unread notifications" : "Nothing here yet"}
          description={
            unreadOnly
              ? "You are all caught up. Switch to All to see older notifications."
              : "When a possible match appears or a claim is reviewed, you will see it here."
          }
          action={
            unreadOnly ? (
              <button
                type="button"
                onClick={() => {
                  const next = new URLSearchParams(params);
                  next.delete("filter");
                  setParams(next, { replace: true });
                }}
                className="text-sm font-semibold text-brand-strong hover:underline"
              >
                Show all notifications
              </button>
            ) : undefined
          }
        />
      ) : (
        <ul className="surface-card divide-y divide-line overflow-hidden">
          {notificationsQuery.data.items.map((item) => {
            const Icon = iconFor(item.type);
            const href = user ? hrefFor(item, user.role) : null;

            return (
              <li
                key={item.id}
                className={cn(
                  "flex items-start gap-3 px-4 py-4 sm:px-5",
                  !item.is_read && "bg-brand-soft/25",
                )}
              >
                <span
                  className={cn(
                    "mt-0.5 flex h-9 w-9 shrink-0 items-center justify-center rounded-lg",
                    toneFor(item.type),
                  )}
                >
                  <Icon size={18} aria-hidden="true" />
                </span>

                <div className="min-w-0 flex-1">
                  <div className="flex items-start gap-2">
                    {!item.is_read && (
                      <span
                        className="mt-1.5 h-2 w-2 shrink-0 rounded-full bg-brand"
                        aria-label="Unread"
                      />
                    )}
                    <div className="min-w-0">
                      {href ? (
                        <Link
                          to={href}
                          className="text-sm font-semibold text-ink-strong hover:text-brand-strong hover:underline"
                        >
                          {item.title}
                        </Link>
                      ) : (
                        <p className="text-sm font-semibold text-ink-strong">{item.title}</p>
                      )}
                      {item.body && (
                        <p className="mt-0.5 text-sm leading-relaxed text-muted-fg">{item.body}</p>
                      )}
                      <p className="mt-1 text-xs text-muted-fg">{formatRelative(item.created_at)}</p>
                    </div>
                  </div>
                </div>

                {!item.is_read && (
                  <button
                    type="button"
                    onClick={() => markRead.mutate(item.id)}
                    disabled={markRead.isPending}
                    className="shrink-0 rounded-md px-2 py-1 text-xs font-medium text-brand-strong transition-colors hover:bg-brand-soft disabled:opacity-50"
                  >
                    Mark as read
                  </button>
                )}
              </li>
            );
          })}
        </ul>
      )}
    </div>
  );
}
